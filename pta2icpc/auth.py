"""HTTP Basic authentication for the ``/api/v4/`` surface.

The username is fixed (``admin``); the password lives in
``manual/config/config.json`` (``api_password``) and is generated by the
setup GUI. Only ``/api/v4/*`` is guarded — ``/healthz`` and the legacy
``/contests*`` redirects stay open for local self-checks.

The password must never be logged or recorded, with one deliberate
exception: the service entry point prints :func:`credentials_banner` on
startup so the operator can read the credentials off the console. Never log
any ``Authorization`` header.
"""

from __future__ import annotations

import base64
import binascii
import hmac
import secrets

from fastapi import HTTPException, Request

from .models import error_body

API_USERNAME = "admin"

# English letters + digits minus the look-alike characters 0 O 1 l I.
# 57 symbols × 8 chars ≈ 47 bits; no & or quotes so the password pastes
# straight into cdsConfig.xml.
_PASSWORD_ALPHABET = (
    "abcdefghijkmnopqrstuvwxyz"
    "ABCDEFGHJKLMNPQRSTUVWXYZ"
    "23456789"
)
_PASSWORD_LENGTH = 8


def generate_api_password() -> str:
    """A fresh random API password (8 chars from the look-alike-free set)."""
    return "".join(secrets.choice(_PASSWORD_ALPHABET)
                   for _ in range(_PASSWORD_LENGTH))


def check_basic_auth(header: str | None, password: str) -> bool:
    """Validate an ``Authorization`` header against ``admin``/``password``.

    Any malformed input (missing header, non-Basic scheme, bad base64,
    missing colon, non-UTF-8 payload) returns False; both the username and
    the password are compared in constant time.
    """
    if not header:
        return False
    scheme, _, encoded = header.partition(" ")
    if scheme.lower() != "basic" or not encoded:
        return False
    try:
        decoded = base64.b64decode(encoded, validate=True).decode("utf-8")
    except (binascii.Error, ValueError):  # bad base64 or non-UTF-8
        return False
    user, sep, passwd = decoded.partition(":")
    if not sep:
        return False
    return (hmac.compare_digest(user.encode("utf-8"), API_USERNAME.encode())
            and hmac.compare_digest(passwd.encode("utf-8"),
                                    password.encode("utf-8")))


def credentials_banner(password: str) -> str:
    """The startup line showing the API credentials on the console.

    Deliberate exception to the "never print the password" rule (requested
    by the operator): ``Server View User Info: admin / <password>``.
    """
    return f"Server View User Info: {API_USERNAME} / {password}"


def require_api_auth(password: str):
    """Build the app-level dependency guarding ``/api/v4/``.

    An empty ``password`` disables the check entirely (the default app is
    fully open); non-``/api/v4`` paths are never intercepted. A failed
    check raises a spec-shaped 401 that keeps the ``WWW-Authenticate``
    challenge.
    """
    async def dependency(request: Request) -> None:
        if not password:
            return
        path = request.url.path
        if path != "/api/v4" and not path.startswith("/api/v4/"):
            return
        if not check_basic_auth(request.headers.get("authorization"), password):
            raise HTTPException(
                401, error_body(401, "authentication required"),
                headers={"WWW-Authenticate": 'Basic realm="pta2icpc"'})
    return dependency
